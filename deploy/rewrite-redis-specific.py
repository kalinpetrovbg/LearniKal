def main():
    with CATALOG.open(encoding="utf-8-sig", newline="") as source:
        expected = {row["subtopic_slug"] for row in csv.DictReader(source)
                    if row["topic_slug"] == "redis"}
    if set(CASES) != expected or any(len(cases) != 5 for cases in CASES.values()):
        raise ValueError("Redis cases must cover every catalog subtopic with five cases")
    with BANK.open(encoding="utf-8-sig", newline="") as source:
        current = list(csv.DictReader(source))
    preserved = [row for row in current if row["topic_slug"] != "redis"]
    for slug, cases in CASES.items():
        for difficulty, prompt in PROMPTS.items():
            for case in cases:
                preserved.append({"topic_slug": "redis", "subtopic_slug": slug,
                                  "difficulty": str(difficulty), "text": prompt.format(case=case)})
    with BANK.open("w", encoding="utf-8", newline="") as target:
        writer = csv.DictWriter(target, fieldnames=["topic_slug", "subtopic_slug", "difficulty", "text"])
        writer.writeheader()
        writer.writerows(preserved)
    print("Rewrote 1375 Redis questions")


if __name__ == "__main__":
    main()
