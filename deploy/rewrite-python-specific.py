def main():
    with OUTPUT.open(encoding="utf-8-sig", newline="") as source:
        rows = list(csv.DictReader(source))
    preserved = [row for row in rows if row["subtopic_slug"] not in CASES]
    for slug, cases in CASES.items():
        assert len(cases) == 4
        for difficulty, prompt in PROMPTS.items():
            for case in cases:
                preserved.append({"subtopic_slug": slug, "difficulty": str(difficulty),
                                  "text": prompt.format(case=case)})
    with OUTPUT.open("w", encoding="utf-8", newline="") as target:
        writer = csv.DictWriter(target, fieldnames=["subtopic_slug", "difficulty", "text"])
        writer.writeheader()
        writer.writerows(preserved)
    print(f"Rewrote {len(CASES)} Python subtopics")

if __name__ == "__main__":
    main()
